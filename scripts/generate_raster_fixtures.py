def _write_warped_reference(spec: RasterSpec, raster_path: Path) -> Path:
    """Derive ``<stem>_warped.tif`` -- the north-up answer to a rotated source.

    A rotated affine has no correct north-up reading, so a consumer checked
    only against itself can agree with itself and still be wrong; that is
    exactly how rio-tiler's ``read()``/``part()``/``preview()`` disagreed three
    ways with no error. All three validation runs had to hand-build this
    ``WarpedVRT`` before they could say which answer was right. Shipping it
    beside the source makes the right answer part of the case.
    """
    from rasterio.vrt import WarpedVRT

    stem = raster_path.stem.removesuffix("_warped")
    dest = raster_path.with_name(f"{stem}_warped_reference.tif")
    with rasterio.open(raster_path) as src, WarpedVRT(src) as vrt:
        profile = vrt.profile
        profile.update(driver="GTiff")
        with rasterio.open(dest, "w", **profile) as out:
            out.write(vrt.read())
            if src.nodata is not None:
                out.nodata = src.nodata
    return dest


def _write_geographic_twin(spec: RasterSpec, raster_path: Path) -> Path:
    """Reproject *raster_path* to EPSG:4326 beside it — Plan 38 Phase 4.3.

    The geographic half of the CRS-family pair is *derived*, not authored, for
    the reason ``_write_warped_reference`` exists: a hand-authored twin drifts
    away from the file it is the twin of, and the two halves only mean
    anything together if they describe the same ground.
    """
    from rasterio.warp import calculate_default_transform, reproject

    dest = raster_path.with_name(raster_path.name.replace("_projected", "_geographic"))
    with rasterio.open(raster_path) as src:
        transform, width, height = calculate_default_transform(
            src.crs, "EPSG:4326", src.width, src.height, *src.bounds
        )
        profile = src.profile.copy()
        profile.update(
            driver="GTiff",
            crs="EPSG:4326",
            transform=transform,
            width=width,
            height=height,
        )
        with rasterio.open(dest, "w", **profile) as out:
            reproject(
                source=rasterio.band(src, 1),
                destination=rasterio.band(out, 1),
                src_transform=src.transform,
                src_crs=src.crs,
                dst_transform=transform,
                dst_crs="EPSG:4326",
                resampling=Resampling.nearest,
                src_nodata=src.nodata,
                dst_nodata=src.nodata,
            )
            if src.descriptions[0]:
                out.set_band_description(1, src.descriptions[0])
    return dest


def _write_raster(spec: RasterSpec, dest: Path) -> None:
    """Write *spec* to *dest* with explicit, deterministic profile."""
    array = spec.array()
    height, width = array.shape[1], array.shape[2]
    profile = {
        "driver": "GTiff",
        "height": height,
        "width": width,
        "count": array.shape[0],
        "dtype": spec.dtype,
        "crs": spec.crs,
        "transform": spec.resolved_transform(),
    }
    if spec.nodata is not None:
        profile["nodata"] = spec.nodata
    if spec.compression is not None:
        profile["compress"] = spec.compression
    if spec.tiled:
        profile["tiled"] = True
        profile["blockxsize"] = spec.block_size
        profile["blockysize"] = spec.block_size

    # Stale external overviews would otherwise be read back transparently.
    sidecar = dest.with_suffix(dest.suffix + ".ovr")
    if sidecar.exists():
        sidecar.unlink()

    dest.parent.mkdir(parents=True, exist_ok=True)
    with rasterio.open(dest, "w", **profile) as dst:
        dst.write(array)
        if spec.band_names:
            for idx, name in enumerate(spec.band_names, start=1):
                dst.set_band_description(idx, name)
        if spec.scale_factor is not None:
            dst.scales = (spec.scale_factor,) * array.shape[0]
        if spec.colormap is not None:
            dst.write_colormap(1, spec.colormap)
        if spec.tags:
            # Converges with raster/_writer.py, which already does this.
            dst.update_tags(**spec.tags)
        # Internal overviews (COG-style) are written inside the same file.
        if spec.overviews and not spec.external_overviews:
            dst.build_overviews(spec.overviews, Resampling.nearest)
            dst.update_tags(ns="rio_overview", resampling="nearest")

    # External overviews are built in a second pass on the read-only dataset,
    # which makes GDAL emit a sibling ``.ovr`` sidecar instead of embedding.
    if spec.overviews and spec.external_overviews:
        from osgeo import gdal

        gdal.UseExceptions()
        ds = gdal.Open(str(dest), gdal.GA_ReadOnly)
        try:
            ds.BuildOverviews("NEAREST", spec.overviews)
        finally:
            ds = None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate bundled raster fixtures.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any fixture would change instead of writing it.",
    )
    parser.add_argument(
        "--raster-root",
        type=Path,
        default=RASTER_ROOT,
        help="Root directory for raster case folders.",
    )
    return parser.parse_args()


def _emit(spec: RasterSpec | SynthSpec, dest: Path) -> list[Path]:
    """Write *spec* to *dest*; returns every file written, primary first."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(spec, SynthSpec):
        spec.build(dest)
        return [dest]

    _write_raster(spec, dest)
    written = [dest]
    if spec.emit_footprint:
        written.append(_write_footprint(spec, dest))
    if spec.emit_warped_reference:
        written.append(_write_warped_reference(spec, dest))
    if spec.emit_geographic_twin:
        written.append(_write_geographic_twin(spec, dest))
    return written


def _dest_for(spec: RasterSpec | SynthSpec, raster_root: Path) -> Path:
    """Resolve a spec's on-disk primary path.

    Most fixtures live in ``<raster_root>/<case_id>/``; the footprint edge
    cases share a single directory, so ``RasterSpec.case_dir`` overrides it.
    """
    folder = getattr(spec, "case_dir", None) or spec.case_id
    return raster_root / folder / spec.primary


def main() -> int:
    """CLI entrypoint."""
    args = parse_args()
    specs: list[RasterSpec | SynthSpec] = [*_specs(), *_synth_specs()]

    if args.check:
        import tempfile

        stale: list[str] = []
        for spec in specs:
            dest = _dest_for(spec, args.raster_root)
            if not dest.exists():
                stale.append(spec.case_id)
                continue
            with tempfile.TemporaryDirectory() as tmp:
                candidate = Path(tmp) / spec.primary
                for produced in _emit(spec, candidate):
                    committed = dest.with_name(produced.name)
                    if (
                        not committed.exists()
                        or produced.read_bytes() != committed.read_bytes()
                    ):
                        stale.append(spec.case_id)
                        break
        if stale:
            print(f"Raster fixtures out of date: {', '.join(stale)}")
            return 1
        print("All raster fixtures up to date")
        return 0

    for spec in specs:
        dest = _dest_for(spec, args.raster_root)
        for produced in _emit(spec, dest):
            print(f"Wrote {produced.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
